create or replace function public.is_family_member(fid uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.families f
    where f.id = fid and f.owner_id = auth.uid()
  ) or exists (
    select 1 from public.family_members fm
    where fm.family_id = fid and fm.profile_id = auth.uid()
  );
$$;

create or replace function public.my_family_ids()
returns setof uuid
language sql
stable
security definer
set search_path = public
as $$
  select id from public.families where owner_id = auth.uid()
  union
  select family_id from public.family_members where profile_id = auth.uid();
$$;

-- Parent generates a short-lived pair code
create or replace function public.create_pair_code(p_minutes int default 30)
returns table (code text, expires_at timestamptz, family_id uuid)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_family_id uuid;
  v_code text;
  v_expires timestamptz;
begin
  if not exists (select 1 from public.profiles where id = auth.uid() and role = 'parent') then
    raise exception 'Only parents can create pair codes';
  end if;

  select id into v_family_id from public.families where owner_id = auth.uid() limit 1;
  if v_family_id is null then
    insert into public.families (owner_id, name)
    values (auth.uid(), 'My Family')
    returning id into v_family_id;
  end if;

  v_code := upper(substr(md5(random()::text || clock_timestamp()::text), 1, 6));
  v_expires := now() + make_interval(mins => p_minutes);

  insert into public.pair_codes (family_id, code, created_by, expires_at)
  values (v_family_id, v_code, auth.uid(), v_expires);

  return query select v_code, v_expires, v_family_id;
end;
$$;

-- Child redeems pair code to join parent's family
create or replace function public.redeem_pair_code(p_code text)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_row public.pair_codes%rowtype;
begin
  if not exists (select 1 from public.profiles where id = auth.uid() and role = 'child') then
    raise exception 'Only children can redeem pair codes';
  end if;

  select * into v_row
  from public.pair_codes
  where code = upper(trim(p_code))
    and used_at is null
    and expires_at > now()
  for update;

  if not found then
    raise exception 'Invalid or expired pair code';
  end if;

  insert into public.family_members (family_id, profile_id)
  values (v_row.family_id, auth.uid())
  on conflict (family_id, profile_id) do nothing;

  update public.pair_codes
  set used_at = now(), used_by = auth.uid()
  where id = v_row.id;

  return v_row.family_id;
end;
$$;

