-- 1. Profiles (linked to auth.users)
create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  role text not null check (role in ('parent', 'child')),
  display_name text not null default '',
  created_at timestamptz not null default now()
);

-- 2. Families (owned by parent)
create table if not exists public.families (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.profiles (id) on delete cascade,
  name text not null default 'My Family',
  created_at timestamptz not null default now()
);

-- 3. Family Members (children paired into a family)
create table if not exists public.family_members (
  id uuid primary key default gen_random_uuid(),
  family_id uuid not null references public.families (id) on delete cascade,
  profile_id uuid not null references public.profiles (id) on delete cascade,
  joined_at timestamptz not null default now(),
  unique (family_id, profile_id)
);

-- 4. Short-lived Pair Codes (generated by parent, redeemed by child)
create table if not exists public.pair_codes (
  id uuid primary key default gen_random_uuid(),
  family_id uuid not null references public.families (id) on delete cascade,
  code text not null unique,
  created_by uuid not null references public.profiles (id) on delete cascade,
  expires_at timestamptz not null,
  used_at timestamptz,
  used_by uuid references public.profiles (id),
  created_at timestamptz not null default now()
);

-- 5. Specific Domain Filtering (custom block list)
create table if not exists public.block_list (
  id uuid primary key default gen_random_uuid(),
  family_id uuid not null references public.families (id) on delete cascade,
  domain text not null,
  created_by uuid not null references public.profiles (id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (family_id, domain)
);

-- 6. Category-Based Filtering (adult, social, gambling, games, streaming, violence)
create table if not exists public.blocked_categories (
  id uuid primary key default gen_random_uuid(),
  family_id uuid not null references public.families (id) on delete cascade,
  category text not null,
  created_by uuid not null references public.profiles (id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (family_id, category)
);

-- 7. Blocked Apps (package name based blocking)
create table if not exists public.blocked_apps (
  id uuid primary key default gen_random_uuid(),
  family_id uuid not null references public.families (id) on delete cascade,
  package_name text not null,
  app_label text not null default '',
  created_at timestamptz not null default now(),
  unique (family_id, package_name)
);

-- 8. Child Network Activity Logs (recorded by child DNS VPN, monitored by parent)
create table if not exists public.domain_logs (
  id uuid primary key default gen_random_uuid(),
  child_id uuid not null references public.profiles (id) on delete cascade,
  family_id uuid not null references public.families (id) on delete cascade,
  domain text not null,
  action text not null check (action in ('allowed', 'blocked')),
  occurred_at timestamptz not null default now()
);

-- 9. Child App Usage Logs
create table if not exists public.app_usage_logs (
  id uuid primary key default gen_random_uuid(),
  child_id uuid not null references public.profiles (id) on delete cascade,
  family_id uuid not null references public.families (id) on delete cascade,
  package_name text not null,
  app_label text not null default '',
  started_at timestamptz not null,
  ended_at timestamptz,
  duration_seconds integer,
  created_at timestamptz not null default now()
);

-- Indexes for fast lookups & realtime querying
create index if not exists idx_domain_logs_child_time on public.domain_logs (child_id, occurred_at desc);
create index if not exists idx_domain_logs_family_time on public.domain_logs (family_id, occurred_at desc);
create index if not exists idx_app_usage_child_time on public.app_usage_logs (child_id, started_at desc);
create index if not exists idx_block_list_family on public.block_list (family_id);
create index if not exists idx_blocked_categories_family on public.blocked_categories (family_id);
create index if not exists idx_blocked_apps_family on public.blocked_apps (family_id);
create index if not exists idx_pair_codes_code on public.pair_codes (code);

